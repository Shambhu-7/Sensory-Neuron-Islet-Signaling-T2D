cat("Analysis time:\n")
print(Sys.time())

cat("\nQC rule:\n")
cat("Cells: >=500 genes with RPKM > 0\n")
cat("Genes: detected in >=3 retained cells\n")

cat("\nFinal dimensions:\n")
print(dim(expr_qc))

cat("\nFinal cell-type counts:\n")
print(table(meta_qc$cell_subtype))

cat("\nFinal condition counts:\n")
print(table(meta_qc$condition))

cat("\n")
sessionInfo()

sink()

