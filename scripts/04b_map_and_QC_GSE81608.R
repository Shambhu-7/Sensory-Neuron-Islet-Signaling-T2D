
options(stringsAsFactors = FALSE)

project_dir <- normalizePath(".", mustWork = TRUE)

processed_dir <- file.path(project_dir, "data", "processed")
islet_dir <- file.path(project_dir, "results", "islet")
repro_dir <- file.path(project_dir, "reproducibility")

dir.create(processed_dir, recursive = TRUE, showWarnings = FALSE)
dir.create(islet_dir, recursive = TRUE, showWarnings = FALSE)
dir.create(repro_dir, recursive = TRUE, showWarnings = FALSE)

cat("\n============================================\n")
cat("SCRIPT 04b: GSE81608 SAMPLE MAPPING + QC\n")
cat("============================================\n")

# ============================================================
# 1. Load objects generated by Script 04a
# ============================================================

rpkm_raw <- readRDS(
    file.path(
        processed_dir,
        "GSE81608_RPKM_raw_import.rds"
    )
)

meta <- read.csv(
    file.path(
        processed_dir,
        "GSE81608_cell_metadata.csv"
    ),
    check.names = FALSE
)

cat(
    "\nRaw matrix:",
    nrow(rpkm_raw),
    "genes x",
    ncol(rpkm_raw) - 1,
    "cells\n"
)

cat(
    "Metadata rows:",
    nrow(meta),
    "\n"
)

# ============================================================
# 2. Derive Sample_N from GEO title
# ============================================================

title_pattern <-
    "^Pancreatic islet cell sample[[:space:]]+[0-9]+$"

if (!all(
    grepl(
        title_pattern,
        meta$title,
        ignore.case = TRUE
    )
)) {
    stop(
        "Not all GEO titles follow the expected ",
        "'Pancreatic islet cell sample N' pattern."
    )
}

meta$sample_number <- as.integer(
    sub(
        "^Pancreatic islet cell sample[[:space:]]+",
        "",
        meta$title,
        ignore.case = TRUE
    )
)

meta$matrix_column <- paste0(
    "Sample_",
    meta$sample_number
)

expr_cols <- grep(
    "^Sample_[0-9]+$",
    names(rpkm_raw),
    value = TRUE
)

if (length(expr_cols) != 1600L) {
    stop(
        "Expected 1600 Sample_N columns; found ",
        length(expr_cols)
    )
}

if (anyDuplicated(meta$sample_number)) {
    stop("Duplicate GEO sample numbers detected.")
}

if (!setequal(
    meta$matrix_column,
    expr_cols
)) {
    stop(
        "GEO title-derived Sample_N identifiers do not ",
        "exactly match expression columns."
    )
}

# Reorder metadata into exact expression-matrix order

meta_expr <- meta[
    match(
        expr_cols,
        meta$matrix_column
    ),
    ,
    drop = FALSE
]

if (
    anyNA(meta_expr$GSM) ||
    !identical(
        meta_expr$matrix_column,
        expr_cols
    )
) {
    stop(
        "Failed to align GEO metadata with expression columns."
    )
}

cat("\nSample_N mapping: PASS\n")

# ============================================================
# 3. Independent GEO anchor validation
# ============================================================

anchors <- data.frame(
    sample_number = c(
        1L,
        103L,
        1600L
    ),
    expected_GSM = c(
        "GSM2157899",
        "GSM2158001",
        "GSM2159558"
    ),
    stringsAsFactors = FALSE
)

anchor_check <- merge(
    anchors,
    meta_expr[
        ,
        c(
            "sample_number",
            "matrix_column",
            "GSM",
            "donor_id",
            "condition",
            "cell_subtype"
        )
    ],
    by = "sample_number",
    all.x = TRUE,
    sort = FALSE
)

anchor_check$PASS <-
    anchor_check$expected_GSM ==
    anchor_check$GSM

cat("\n============================================\n")
cat("GEO ANCHOR VALIDATION\n")
cat("============================================\n")

print(
    anchor_check,
    row.names = FALSE
)

if (!all(anchor_check$PASS)) {
    stop(
        "GEO anchor validation failed."
    )
}

write.csv(
    anchor_check,
    file.path(
        islet_dir,
        "GSE81608_sample_mapping_anchor_validation.csv"
    ),
    row.names = FALSE
)

# ============================================================
# 4. Convert expression data to numeric matrix
# ============================================================

cat("\nConverting RPKM expression to matrix...\n")

expr <- as.matrix(
    rpkm_raw[
        ,
        expr_cols,
        drop = FALSE
    ]
)

storage.mode(expr) <- "double"

rownames(expr) <- as.character(
    rpkm_raw$gene.id
)

cat(
    "Expression matrix:",
    nrow(expr),
    "x",
    ncol(expr),
    "\n"
)

# ============================================================
# 5. Cell QC
#
# Published reproducible filter:
# retain cells with >=500 detected genes
# ============================================================

cat("\nCalculating detected genes per cell...\n")

detected_genes_per_cell <- colSums(
    expr > 0
)

meta_expr$n_detected_genes <-
    detected_genes_per_cell[
        meta_expr$matrix_column
    ]

meta_expr$QC_cell_pass <-
    meta_expr$n_detected_genes >= 500

cat("\n============================================\n")
cat("CELL QC\n")
cat("============================================\n")

cat(
    "Cells before QC:",
    nrow(meta_expr),
    "\n"
)

cat(
    "Cells passing >=500 detected genes:",
    sum(meta_expr$QC_cell_pass),
    "\n"
)

cat(
    "Cells removed:",
    sum(!meta_expr$QC_cell_pass),
    "\n"
)

cat("\nCell type counts after cell QC:\n")

print(
    table(
        meta_expr$cell_subtype[
            meta_expr$QC_cell_pass
        ]
    )
)

cat("\nCondition counts after cell QC:\n")

print(
    table(
        meta_expr$condition[
            meta_expr$QC_cell_pass
        ]
    )
)

# ============================================================
# 6. Gene QC
#
# retain genes detected in >=3 retained cells
# ============================================================

keep_cell_columns <-
    meta_expr$matrix_column[
        meta_expr$QC_cell_pass
    ]

expr_cellQC <- expr[
    ,
    keep_cell_columns,
    drop = FALSE
]

cat("\nCalculating gene detection after cell QC...\n")

cells_per_gene <- rowSums(
    expr_cellQC > 0
)

keep_genes <-
    cells_per_gene >= 3

cat("\n============================================\n")
cat("GENE QC\n")
cat("============================================\n")

cat(
    "Genes before QC:",
    nrow(expr),
    "\n"
)

cat(
    "Genes detected in >=3 retained cells:",
    sum(keep_genes),
    "\n"
)

cat(
    "Genes removed:",
    sum(!keep_genes),
    "\n"
)

expr_qc <- expr_cellQC[
    keep_genes,
    ,
    drop = FALSE
]

meta_qc <- meta_expr[
    meta_expr$QC_cell_pass,
    ,
    drop = FALSE
]

# Ensure exact same cell ordering

meta_qc <- meta_qc[
    match(
        colnames(expr_qc),
        meta_qc$matrix_column
    ),
    ,
    drop = FALSE
]

stopifnot(
    identical(
        colnames(expr_qc),
        meta_qc$matrix_column
    )
)

# ============================================================
# 7. Expected published dimensions
# ============================================================

cat("\n============================================\n")
cat("PUBLISHED-DIMENSION VALIDATION\n")
cat("============================================\n")

cat(
    "Observed retained cells:",
    ncol(expr_qc),
    "\n"
)

cat(
    "Expected retained cells: 1492\n"
)

cat(
    "Observed retained genes:",
    nrow(expr_qc),
    "\n"
)

cat(
    "Expected retained genes: 28403\n"
)

cell_count_pass <-
    ncol(expr_qc) == 1492L

gene_count_pass <-
    nrow(expr_qc) == 28403L

cat(
    "Cell-count validation:",
    ifelse(
        cell_count_pass,
        "PASS",
        "CHECK"
    ),
    "\n"
)

cat(
    "Gene-count validation:",
    ifelse(
        gene_count_pass,
        "PASS",
        "CHECK"
    ),
    "\n"
)

# ============================================================
# 8. Cell-type validation
# ============================================================

expected_celltypes <- c(
    alpha = 886L,
    beta = 472L,
    delta = 49L,
    PP = 85L
)

observed_celltypes <- table(
    factor(
        meta_qc$cell_subtype,
        levels = names(expected_celltypes)
    )
)

celltype_validation <- data.frame(
    cell_subtype = names(expected_celltypes),
    expected = as.integer(expected_celltypes),
    observed = as.integer(observed_celltypes),
    stringsAsFactors = FALSE
)

celltype_validation$PASS <-
    celltype_validation$expected ==
    celltype_validation$observed

cat("\nCell-type validation:\n")

print(
    celltype_validation,
    row.names = FALSE
)

# ============================================================
# 9. Endocrine marker sanity check
#
# Entrez IDs:
# INS  = 3630
# GCG  = 2641
# SST  = 6750
# PPY  = 5539
# ============================================================

marker_info <- data.frame(
    gene = c(
        "INS",
        "GCG",
        "SST",
        "PPY"
    ),
    entrez = c(
        "3630",
        "2641",
        "6750",
        "5539"
    ),
    expected_celltype = c(
        "beta",
        "alpha",
        "delta",
        "PP"
    ),
    stringsAsFactors = FALSE
)

marker_results <- list()

for (i in seq_len(nrow(marker_info))) {

    gene <- marker_info$gene[i]
    entrez <- marker_info$entrez[i]

    if (!(entrez %in% rownames(expr_qc))) {

        marker_results[[gene]] <- data.frame(
            gene = gene,
            expected_celltype =
                marker_info$expected_celltype[i],
            observed_top_celltype = NA_character_,
            top_mean_RPKM = NA_real_,
            PASS = FALSE,
            stringsAsFactors = FALSE
        )

        next
    }

    means <- sapply(
        c(
            "alpha",
            "beta",
            "delta",
            "PP"
        ),
        function(ct) {

            idx <- which(
                meta_qc$cell_subtype == ct
            )

            mean(
                expr_qc[
                    entrez,
                    idx
                ],
                na.rm = TRUE
            )
        }
    )

    observed_top <-
        names(
            which.max(means)
        )

    marker_results[[gene]] <- data.frame(
        gene = gene,
        expected_celltype =
            marker_info$expected_celltype[i],
        observed_top_celltype =
            observed_top,
        top_mean_RPKM =
            unname(
                max(means)
            ),
        PASS =
            observed_top ==
            marker_info$expected_celltype[i],
        stringsAsFactors = FALSE
    )
}

marker_validation <- do.call(
    rbind,
    marker_results
)

cat("\n============================================\n")
cat("ENDOCRINE MARKER SANITY CHECK\n")
cat("============================================\n")

print(
    marker_validation,
    row.names = FALSE
)

# ============================================================
# 10. Donor balance after QC
# ============================================================

donor_balance <- as.data.frame(
    table(
        meta_qc$donor_id,
        meta_qc$condition,
        meta_qc$cell_subtype
    ),
    stringsAsFactors = FALSE
)

names(donor_balance) <- c(
    "donor_id",
    "condition",
    "cell_subtype",
    "n_cells"
)

donor_balance <- donor_balance[
    donor_balance$n_cells > 0,
    ,
    drop = FALSE
]

cat("\n============================================\n")
cat("DONOR BALANCE AFTER QC\n")
cat("============================================\n")

print(
    donor_balance,
    row.names = FALSE
)

# ============================================================
# 11. Save frozen QC dataset
# ============================================================

saveRDS(
    expr_qc,
    file.path(
        processed_dir,
        "GSE81608_RPKM_QC_1492cells.rds"
    ),
    compress = TRUE
)

write.csv(
    meta_expr,
    file.path(
        processed_dir,
        "GSE81608_all1600_cells_with_QC_status.csv"
    ),
    row.names = FALSE
)

write.csv(
    meta_qc,
    file.path(
        processed_dir,
        "GSE81608_QC_1492_cell_metadata.csv"
    ),
    row.names = FALSE
)

write.csv(
    celltype_validation,
    file.path(
        islet_dir,
        "GSE81608_QC_celltype_validation.csv"
    ),
    row.names = FALSE
)

write.csv(
    marker_validation,
    file.path(
        islet_dir,
        "GSE81608_QC_marker_validation.csv"
    ),
    row.names = FALSE
)

write.csv(
    donor_balance,
    file.path(
        islet_dir,
        "GSE81608_QC_donor_celltype_balance.csv"
    ),
    row.names = FALSE
)

# ============================================================
# 12. Final validation
# ============================================================

overall_pass <-
    cell_count_pass &&
    gene_count_pass &&
    all(celltype_validation$PASS) &&
    all(marker_validation$PASS)

cat("\n============================================\n")
cat("FINAL GSE81608 QC VALIDATION\n")
cat("============================================\n")

cat(
    "Sample mapping anchors:",
    ifelse(
        all(anchor_check$PASS),
        "PASS",
        "FAIL"
    ),
    "\n"
)

cat(
    "1492-cell validation:",
    ifelse(
        cell_count_pass,
        "PASS",
        "CHECK"
    ),
    "\n"
)

cat(
    "28403-gene validation:",
    ifelse(
        gene_count_pass,
        "PASS",
        "CHECK"
    ),
    "\n"
)

cat(
    "Cell-type counts:",
    ifelse(
        all(celltype_validation$PASS),
        "PASS",
        "CHECK"
    ),
    "\n"
)

cat(
    "Endocrine marker identities:",
    ifelse(
        all(marker_validation$PASS),
        "PASS",
        "CHECK"
    ),
    "\n"
)

cat(
    "\nOVERALL:",
    ifelse(
        overall_pass,
        "PASS",
        "CHECK"
    ),
    "\n"
)

